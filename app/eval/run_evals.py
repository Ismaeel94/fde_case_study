"""
Simple evaluation runner for the EY case study assistant.

Usage:
    python evals/run_evals.py --cases evals/eval_cases.json

Environment variables:
    ASSISTANT_API_URL      e.g. http://127.0.0.1:8000/api/v1/messages
    SALES_SESSION          session cookie value for sales_user
    SUPPORT_SESSION        session cookie value for support_user
    ADMIN_SESSION          session cookie value for admin
    SESSION_COOKIE_NAME    default: session

This runner intentionally does not make hard pass/fail judgements about LLM quality.
It records responses, latency and expected criteria so you can inspect LangSmith traces
and mark the final result.
"""

from __future__ import annotations

import argparse
import json
import os
import time
from pathlib import Path
from typing import Any

import httpx


def get_session_for_role(role: str) -> str:
    env_by_role = {
        "sales_user": "SALES_SESSION",
        "support_user": "SUPPORT_SESSION",
        "admin": "ADMIN_SESSION",
    }

    env_name = env_by_role.get(role)
    if not env_name:
        raise ValueError(f"Unknown role: {role}")

    value = os.getenv(env_name)
    if not value:
        raise RuntimeError(
            f"Missing {env_name}. Log in as {role}, copy the session cookie, "
            f"and set it before running evals."
        )

    return value


def extract_response_text(payload: Any) -> str:
    """
    Adjust this if your /messages endpoint returns a different shape.
    Common shapes:
      {"response": "..."}
      {"message": "..."}
      {"content": "..."}
      {"messages": [...]}
    """
    if isinstance(payload, dict):
        for key in ("response", "final_response", "message", "content", "answer"):
            if key in payload and isinstance(payload[key], str):
                return payload[key]

        if "messages" in payload and isinstance(payload["messages"], list):
            messages = payload["messages"]
            if messages:
                last = messages[-1]
                if isinstance(last, dict):
                    return str(last.get("content", last))
                return str(last)

    return str(payload)


def run_case(
    client: httpx.Client,
    api_url: str,
    case: dict[str, Any],
    session_cookie_name: str,
) -> dict[str, Any]:
    role = case["role"]
    session = get_session_for_role(role)

    headers = {
        # Useful for correlating API logs / LangSmith traces if you propagate it.
        "X-Eval-Case-Id": case["id"],
        "X-Eval-User-Role": role,
    }

    cookies = {
        session_cookie_name: session,
    }

    started = time.perf_counter()

    try:
        response = client.post(
            api_url,
            json={"message": case["query"]},
            headers=headers,
            cookies=cookies,
            timeout=120,
        )

        latency_ms = round((time.perf_counter() - started) * 1000, 2)

        try:
            payload = response.json()
        except Exception:
            payload = response.text

        return {
            "id": case["id"],
            "role": role,
            "query": case["query"],
            "status_code": response.status_code,
            "latency_ms": latency_ms,
            "expected": case["expected"],
            "response_text": extract_response_text(payload),
            "raw_response": payload,
            "manual_review": {
                "correct_tool_selection": None,
                "grounded_in_database": None,
                "rbac_respected": None,
                "recommended_next_action_reasonable": None,
                "overall_result": "REVIEW_REQUIRED",
                "langsmith_trace_url": "",
                "notes": "",
            },
        }

    except Exception as exc:
        latency_ms = round((time.perf_counter() - started) * 1000, 2)

        return {
            "id": case["id"],
            "role": role,
            "query": case["query"],
            "status_code": None,
            "latency_ms": latency_ms,
            "expected": case["expected"],
            "response_text": "",
            "raw_response": None,
            "error": repr(exc),
            "manual_review": {
                "correct_tool_selection": None,
                "grounded_in_database": None,
                "rbac_respected": None,
                "recommended_next_action_reasonable": None,
                "overall_result": "ERROR",
                "langsmith_trace_url": "",
                "notes": "",
            },
        }


def write_markdown_report(results: list[dict[str, Any]], output_path: Path) -> None:
    lines = [
        "# Evaluation Results",
        "",
        "These results were generated by the evaluation runner. "
        "Final pass/fail values should be completed after inspecting API logs and LangSmith traces.",
        "",
        "| ID | Role | Status | Latency ms | Overall | Query |",
        "|---|---|---:|---:|---|---|",
    ]

    for result in results:
        manual = result.get("manual_review", {})
        query = result["query"].replace("|", "\\|")
        lines.append(
            f"| {result['id']} | {result['role']} | {result.get('status_code')} | "
            f"{result.get('latency_ms')} | {manual.get('overall_result')} | {query} |"
        )

    lines.extend(
        [
            "",
            "## Manual review checklist",
            "",
            "For each case, inspect the LangSmith trace and mark:",
            "",
            "- Correct tool/node selection",
            "- Response grounded in PostgreSQL results",
            "- RBAC respected",
            "- Recommended next action reasonable",
            "",
        ]
    )

    output_path.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--cases", default="evals/eval_cases.json")
    parser.add_argument("--output-dir", default="eval_results")
    args = parser.parse_args()

    api_url = os.getenv("ASSISTANT_API_URL", "http://127.0.0.1:8000/api/v1/messages")
    session_cookie_name = os.getenv("SESSION_COOKIE_NAME", "session")

    cases_path = Path(args.cases)
    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    cases = json.loads(cases_path.read_text(encoding="utf-8"))

    results = []

    with httpx.Client() as client:
        for case in cases:
            print(f"Running {case['id']} as {case['role']}...")
            result = run_case(client, api_url, case, session_cookie_name)
            results.append(result)
            print(
                f"  status={result.get('status_code')} "
                f"latency={result.get('latency_ms')}ms"
            )

    json_path = output_dir / "eval_results.json"
    md_path = output_dir / "eval_results.md"

    json_path.write_text(json.dumps(results, indent=2), encoding="utf-8")
    write_markdown_report(results, md_path)

    print()
    print(f"Wrote {json_path}")
    print(f"Wrote {md_path}")


if __name__ == "__main__":
    main()
